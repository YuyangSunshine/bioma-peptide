from __future__ import annotations

from pathlib import Path
from typing import Any, Dict

from bioma.backends.analysis.workspace import AnalysisState
from bioma.backends.analysis.services.pdf_service import export_markdown_to_pdf
from bioma.backends.analysis.services.reporting_service import (
    build_report_markdown,
    build_report_outline,
    build_report_version_entry,
    normalize_visualization_paths_for_report,
    resolve_report_dir,
    validate_report,
    write_report_file,
)
from bioma.backends.analysis.tools.report_tools import generate_report_body_tool


def run_report_node(state: AnalysisState) -> Dict[str, Any]:
    """
    Reporting node:
    - consumes requirement + analysis artifacts + visualizations
    - generates formal markdown report
    - validates and writes report artifact
    """
    task_id = str(state.get("task_id") or "task")
    requirement = state.get("stable_requirement") or {}
    experiment_background = state.get("experiment_background") or {}
    data_profile = state.get("data_profile") or {}
    analysis_results = state.get("analysis_results") or {}
    chart_plan = state.get("chart_plan") or []
    visualizations = state.get("visualizations") or []
    prior_versions = list(state.get("report_versions") or [])
    artifact_root = str(state.get("artifact_root") or "artifacts")
    report_dir = resolve_report_dir(task_id, artifact_root)
    visualizations_for_report = normalize_visualization_paths_for_report(
        visualizations=visualizations,
        report_dir=report_dir,
    )

    if not data_profile:
        return {
            "report_outline": {},
            "final_report": "",
            "report_versions": prior_versions,
            "active_report_id": None,
            "report_validation": {},
            "error_code": "MISSING_DATA_PROFILE",
            "error_detail": "run_report_node requires data_profile.",
            "status": "failed",
        }

    # reporting should work even if visualizations is empty
    report_outline = build_report_outline(
        requirement=requirement,
        analysis_results=analysis_results,
        visualizations=visualizations_for_report,
    )

    try:
        body_markdown = generate_report_body_tool.invoke(
            {
                "requirement": requirement,
                "experiment_background": experiment_background,
                "data_profile": data_profile,
                "analysis_results": analysis_results,
                "chart_plan": chart_plan,
                "visualizations": visualizations_for_report,
            }
        )
    except Exception as e:
        return {
            "report_outline": report_outline,
            "final_report": "",
            "report_versions": prior_versions,
            "active_report_id": None,
            "report_validation": {},
            "error_code": "REPORT_BODY_GENERATION_FAILED",
            "error_detail": repr(e),
            "status": "failed",
        }

    full_report_text = build_report_markdown(
        requirement=requirement,
        experiment_background=experiment_background,
        body_markdown=body_markdown,
        visualizations=visualizations_for_report,
    )

    report_validation = validate_report(
        report_text=full_report_text,
        analysis_results=analysis_results,
        visualizations=visualizations_for_report,
        report_dir=report_dir,
    )

    report_id, report_path = write_report_file(
        report_dir=report_dir,
        report_text=full_report_text,
    )

    pdf_ok, pdf_path, pdf_err = export_markdown_to_pdf(
        md_path=report_path,
        project_root=str(Path(artifact_root).resolve().parent),
    )
    final_report_pdf = pdf_path if pdf_ok else None

    version_entry = build_report_version_entry(
        report_id=report_id,
        report_path=report_path,
        note="Generated by run_report_node",
        analysis_results=analysis_results,
        visualizations=visualizations,
    )
    if final_report_pdf:
        version_entry["report_pdf_path"] = final_report_pdf
    elif pdf_err:
        version_entry["pdf_error"] = pdf_err
    updated_versions = prior_versions + [version_entry]

    return {
        "report_outline": report_outline,
        "final_report": report_path,
        "final_report_pdf": final_report_pdf,
        "report_versions": updated_versions,
        "active_report_id": report_id,
        "report_validation": report_validation,
        "error_code": None,
        "error_detail": None,
        "status": "active",
    }
